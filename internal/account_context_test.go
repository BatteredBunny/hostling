func TestFrontendContextAPI(t *testing.T) {
	ts := newTestServer(
		t,
		func(c *Config) { c.Branding = "Custom brand"; c.Tagline = "Custom tagline" },
	)
	admin := ts.registerAdmin()
	user, userID := ts.registerUser(admin)
	for _, tt := range []struct {
		name            string
		client          *testClient
		loggedIn, admin bool
		accountID       uint
	}{{"anonymous", ts.newClient(), false, false, 0}, {"user", user, true, false, userID}, {"admin", admin, true, true, ts.adminID()}} {
		t.Run(tt.name, func(t *testing.T) {
			var context FrontendContext
			tt.client.getJSON("/api/context", &context)
			if context.Branding != "Custom brand" || context.Tagline != "Custom tagline" ||
				context.LoggedIn != tt.loggedIn ||
				context.IsAdmin != tt.admin ||
				context.AccountID != tt.accountID ||
				context.HasAdminWarning != tt.admin {
				t.Fatalf("unexpected context: %+v", context)
			}
			if context.Providers == nil {
				t.Fatal("providers must be an array")
			}
			if tt.client.lastHeader.Get("Cache-Control") != "no-store" {
				t.Fatal("context must not be cached")
			}
		})
	}
	ts.app.providersMutex.Lock()
	ts.app.configuredProviders = []string{"github", "openid-connect"}
	ts.app.providersMutex.Unlock()
	var context FrontendContext
	admin.getJSON("/api/context", &context)
	if !slices.Equal(context.Providers, []string{"github", "openid-connect"}) {
		t.Fatalf("unexpected provider identifiers: %v", context.Providers)
	}
}

func TestAstroPagesAndAccess(t *testing.T) {
	ts := newTestServer(t)
	admin := ts.registerAdmin()
	user, _ := ts.registerUser(admin)
	anon := ts.newClient()
	for _, page := range []string{"/gallery", "/tokens", "/settings", "/admin"} {
		if status, _ := anon.get(page); status != http.StatusTemporaryRedirect {
			t.Errorf("anonymous %s status %d", page, status)
		}
		status, body := admin.get(page)
		if status != http.StatusOK || !strings.Contains(body, "astro-island") {
			t.Errorf("%s was not generated by Astro: %d", page, status)
		}
		if strings.Contains(body, "hostling-runtime-head") ||
			strings.Contains(body, "hostling-navigation") {
			t.Errorf("%s contains server injection markers", page)
		}
	}
	if status, _ := user.get("/admin"); status != http.StatusTemporaryRedirect {
		t.Fatal("user accessed admin page")
	}
	for _, page := range []string{"/", "/login", "/register"} {
		if status, body := anon.get(
			page,
		); status != http.StatusOK ||
			!strings.Contains(body, "astro-island") {
			t.Errorf("public page %s: %d", page, status)
		}
	}
}
